import { useCallback, useEffect, useMemo, useState } from 'react'
import DownloadRoundedIcon from '@mui/icons-material/DownloadRounded'
import type { AcademicPeriod } from '@/features/dashboard'
import { useDepartmentOptions } from '@/features/departments/lib/useDepartmentOptions'
import { formatDateTime, formatFileSize } from '@/features/programs/lib/format'
import { downloadBlob } from '@/shared/download'
import { notify } from '@/shared/toast'
import { downloadReport, listReports } from '../api/reportsApi'
import { getReportErrorMessage } from '../lib/deliver'
import { FILE_TYPE_LABELS } from '../lib/labels'
import {
  errorAlertClassName,
  filterInputClassName,
  filterLabelClassName,
  filterSelectClassName,
  secondaryButtonClassName,
} from '../lib/ui'
import {
  REPORT_TYPE_LABELS,
  type GeneratedReport,
  type ReportPaginationMeta,
  type ReportType,
} from '../types'

type ReportArchiveSectionProps = {
  periods: AcademicPeriod[]
  /** Faculty see only the reports they generated; the copy says so. */
  ownOnly: boolean
  /** Bumped by the page after every generation so the new row appears without a manual refresh. */
  refreshSignal: number
}

type PaginationItem = number | 'ellipsis'

const defaultMeta: ReportPaginationMeta = {
  current_page: 1,
  from: null,
  last_page: 1,
  path: '',
  per_page: 20,
  to: null,
  total: 0,
}

const COLUMNS = ['Report', 'Type', 'Period', 'Generated by', 'Generated', 'Size', 'Download']
const skeletonRows = Array.from({ length: 5 }, (_, index) => index)

const paginationButtonClassName =
  'cursor-pointer border border-line px-3 py-2 text-sm font-medium text-ink transition-colors hover:bg-hover-tint disabled:cursor-not-allowed disabled:opacity-45 rounded-md'

function Spinner() {
  return <span className="h-4 w-4 animate-spin rounded-full border-2 border-line border-t-primary-accent" />
}

function getPaginationItems(currentPage: number, lastPage: number): PaginationItem[] {
  const pageSet = new Set<number>([1, lastPage, currentPage - 1, currentPage, currentPage + 1])
  if (currentPage <= 3) {
    pageSet.add(2)
    pageSet.add(3)
  }
  if (currentPage >= lastPage - 2) {
    pageSet.add(lastPage - 1)
    pageSet.add(lastPage - 2)
  }
  const pages = Array.from(pageSet)
    .filter((page) => page >= 1 && page <= lastPage)
    .sort((left, right) => left - right)
  return pages.reduce<PaginationItem[]>((items, page, index) => {
    const previousPage = pages[index - 1]
    if (previousPage && page - previousPage > 1) {
      items.push('ellipsis')
    }
    items.push(page)
    return items
  }, [])
}

function TableHead() {
  return (
    <thead>
      <tr className="border-b border-divider bg-surface-tint text-left text-xs font-semibold uppercase tracking-[0.12em] text-label">
        {COLUMNS.map((column) => (
          <th key={column} className={['px-5 py-3', column === 'Download' ? 'text-right' : ''].join(' ')}>
            {column}
          </th>
        ))}
      </tr>
    </thead>
  )
}

/**
 * The archive (spec Module 7 §4): every generated document, newest first, searchable and filterable
 * by type and period. Files are immutable — regenerating adds a row, it never replaces one.
 */
export default function ReportArchiveSection({ periods, ownOnly, refreshSignal }: ReportArchiveSectionProps) {
  const [reports, setReports] = useState<GeneratedReport[]>([])
  const [meta, setMeta] = useState<ReportPaginationMeta>(defaultMeta)
  const [page, setPage] = useState(1)
  const [perPage, setPerPage] = useState(defaultMeta.per_page)
  const [typeFilter, setTypeFilter] = useState<ReportType | ''>('')
  const [periodFilter, setPeriodFilter] = useState('')
  const [departmentFilter, setDepartmentFilter] = useState('')
  const { isCampusWide, departments } = useDepartmentOptions()
  const [searchInput, setSearchInput] = useState('')
  const [search, setSearch] = useState('')
  const [loading, setLoading] = useState(true)
  const [errorMessage, setErrorMessage] = useState<string | null>(null)
  const [downloadingId, setDownloadingId] = useState<string | null>(null)

  // Search debounces 350 ms and resets to page 1 (UI guidelines §7).
  useEffect(() => {
    const handle = window.setTimeout(() => {
      setSearch(searchInput.trim())
      setPage(1)
    }, 350)
    return () => window.clearTimeout(handle)
  }, [searchInput])

  const load = useCallback(async () => {
    setLoading(true)
    setErrorMessage(null)
    try {
      const response = await listReports({
        page,
        per_page: perPage,
        type: typeFilter,
        periodId: periodFilter,
        search,
        departmentId: departmentFilter,
      })
      setReports(response.data)
      setMeta(response.meta)
    } catch (error) {
      setErrorMessage(getReportErrorMessage(error))
    } finally {
      setLoading(false)
    }
  }, [departmentFilter, page, perPage, periodFilter, search, typeFilter])

  useEffect(() => {
    void load()
  }, [load, refreshSignal])

  const handleDownload = async (report: GeneratedReport) => {
    setDownloadingId(report.id)
    try {
      const blob = await downloadReport(report.id)
      downloadBlob(blob, report.filename)
    } catch (error) {
      notify.error(getReportErrorMessage(error))
    } finally {
      setDownloadingId(null)
    }
  }

  const paginationItems = useMemo(
    () => getPaginationItems(meta.current_page, meta.last_page),
    [meta.current_page, meta.last_page],
  )

  const countLabel = useMemo(() => {
    if (!meta.total) return 'No reports yet'
    return `Showing ${meta.from ?? 0}-${meta.to ?? 0} of ${meta.total} reports`
  }, [meta.from, meta.to, meta.total])

  return (
    <section aria-labelledby="report-archive-title" className="overflow-hidden rounded-lg border border-line bg-surface">
      <div className="flex flex-col gap-3 border-b border-divider px-5 py-4 lg:flex-row lg:items-center lg:justify-between">
        <div>
          <h5 id="report-archive-title" className="text-lg font-semibold tracking-[-0.02em] text-ink">
            Archive
          </h5>
          <p className="mt-1 text-sm text-muted">
            {ownOnly
              ? 'Reports you have generated. Files never change once generated; generate again for a fresh copy.'
              : 'Every report generated on the system. Files never change once generated; generating again adds a new entry.'}
          </p>
        </div>
        <p className="text-sm text-muted">{countLabel}</p>
      </div>

      <div
        className={[
          'grid gap-3 border-b border-divider px-5 py-4 md:grid-cols-2 xl:items-end',
          isCampusWide
            ? 'xl:grid-cols-[minmax(0,2fr)_repeat(4,minmax(0,1fr))]'
            : 'xl:grid-cols-[minmax(0,2fr)_repeat(3,minmax(0,1fr))]',
        ].join(' ')}
      >
        <label className="flex flex-col gap-1.5">
          <span className={filterLabelClassName}>Search</span>
          <input
            type="search"
            value={searchInput}
            placeholder="Search by report name"
            onChange={(event) => setSearchInput(event.target.value)}
            className={filterInputClassName}
          />
        </label>

        <label className="flex flex-col gap-1.5">
          <span className={filterLabelClassName}>Type</span>
          <select
            value={typeFilter}
            onChange={(event) => {
              setTypeFilter(event.target.value as ReportType | '')
              setPage(1)
            }}
            className={filterSelectClassName}
          >
            <option value="">All types</option>
            {(Object.keys(REPORT_TYPE_LABELS) as ReportType[]).map((type) => (
              <option key={type} value={type}>
                {REPORT_TYPE_LABELS[type]}
              </option>
            ))}
          </select>
        </label>

        <label className="flex flex-col gap-1.5">
          <span className={filterLabelClassName}>Period</span>
          <select
            value={periodFilter}
            onChange={(event) => {
              setPeriodFilter(event.target.value)
              setPage(1)
            }}
            className={filterSelectClassName}
          >
            <option value="">All periods</option>
            {periods.map((period) => (
              <option key={period.id} value={period.id}>
                {period.label}
              </option>
            ))}
          </select>
        </label>

        {isCampusWide ? (
          <label className="flex flex-col gap-1.5">
            <span className={filterLabelClassName}>Department</span>
            <select
              value={departmentFilter}
              onChange={(event) => {
                setDepartmentFilter(event.target.value)
                setPage(1)
              }}
              className={filterSelectClassName}
            >
              <option value="">All departments</option>
              {departments.map((department) => (
                <option key={department.id} value={department.id}>
                  {department.code} — {department.name}
                </option>
              ))}
            </select>
          </label>
        ) : null}

        <label className="flex flex-col gap-1.5">
          <span className={filterLabelClassName}>Rows</span>
          <select
            value={perPage}
            onChange={(event) => {
              setPerPage(Number(event.target.value))
              setPage(1)
            }}
            className={filterSelectClassName}
          >
            <option value={20}>20</option>
            <option value={50}>50</option>
            <option value={100}>100</option>
          </select>
        </label>
      </div>

      {loading ? (
        <div aria-busy="true" aria-live="polite">
          <div className="flex items-center gap-3 border-b border-divider px-5 py-3 text-sm text-muted">
            <Spinner />
            Loading reports...
          </div>
          <div className="overflow-x-auto">
            <table className="min-w-[1080px] w-full table-auto border-collapse">
              <TableHead />
              <tbody>
                {skeletonRows.map((row) => (
                  <tr key={row} className="border-b border-row-divider last:border-b-0">
                    {COLUMNS.map((column) => (
                      <td key={column} className="px-5 py-4">
                        <span className="block h-4 w-full max-w-[160px] animate-pulse bg-skeleton" />
                      </td>
                    ))}
                  </tr>
                ))}
              </tbody>
            </table>
          </div>
        </div>
      ) : errorMessage ? (
        <div className="space-y-4 px-5 py-6">
          <div role="alert" className={errorAlertClassName}>
            {errorMessage}
          </div>
          <button type="button" onClick={() => void load()} className={secondaryButtonClassName}>
            Retry
          </button>
        </div>
      ) : (
        <>
          <div className="overflow-x-auto">
            <table className="min-w-[1080px] w-full table-auto border-collapse">
              <TableHead />
              <tbody>
                {reports.length === 0 ? (
                  <tr>
                    <td colSpan={COLUMNS.length} className="px-5 py-12 text-center text-sm text-muted">
                      {search || typeFilter || periodFilter || departmentFilter
                        ? 'No reports match these filters.'
                        : 'No reports have been generated yet. Use a generator above to create the first one.'}
                    </td>
                  </tr>
                ) : (
                  reports.map((report) => (
                    <tr
                      key={report.id}
                      className="border-b border-row-divider text-sm text-cell last:border-b-0 hover:bg-row-hover"
                    >
                      <td className="max-w-[420px] px-5 py-4">
                        <p className="font-medium text-ink">{report.title}</p>
                        <p className="mt-0.5 truncate text-xs text-muted-alt">{report.filename}</p>
                      </td>
                      <td className="px-5 py-4">
                        <span className="inline-flex whitespace-nowrap rounded-md border border-line bg-surface-tint px-2.5 py-1 text-xs font-medium text-ink">
                          {REPORT_TYPE_LABELS[report.reportType] ?? report.reportType}
                          <span className="ml-1.5 text-muted">{FILE_TYPE_LABELS[report.fileType] ?? report.fileType}</span>
                        </span>
                      </td>
                      <td className="px-5 py-4 whitespace-nowrap">{report.periodLabel ?? '-'}</td>
                      <td className="px-5 py-4">{report.generatedByName ?? '-'}</td>
                      <td className="px-5 py-4 whitespace-nowrap">{formatDateTime(report.createdAt)}</td>
                      <td className="px-5 py-4 whitespace-nowrap">
                        {report.sizeBytes == null ? '-' : formatFileSize(report.sizeBytes)}
                      </td>
                      <td className="px-5 py-4">
                        <div className="flex justify-end">
                          <button
                            type="button"
                            aria-label={`Download ${report.title}`}
                            title="Download"
                            disabled={downloadingId === report.id}
                            onClick={() => void handleDownload(report)}
                            className="flex h-9 w-9 cursor-pointer items-center justify-center border border-line text-ink transition-colors hover:bg-hover-tint disabled:cursor-not-allowed disabled:opacity-45 rounded-md"
                          >
                            {downloadingId === report.id ? <Spinner /> : <DownloadRoundedIcon fontSize="small" />}
                          </button>
                        </div>
                      </td>
                    </tr>
                  ))
                )}
              </tbody>
            </table>
          </div>

          <div className="flex flex-col gap-4 border-t border-divider px-5 py-4 lg:flex-row lg:items-center lg:justify-between">
            <p className="text-sm text-muted">
              Page {meta.current_page} of {meta.last_page}
            </p>
            <div className="flex flex-wrap items-center gap-2">
              <button
                type="button"
                disabled={meta.current_page <= 1}
                onClick={() => setPage((current) => Math.max(1, current - 1))}
                className={paginationButtonClassName}
              >
                Previous
              </button>
              {paginationItems.map((item, index) =>
                item === 'ellipsis' ? (
                  <span key={`ellipsis-${index}`} className="px-1 text-sm text-muted-faint">
                    ...
                  </span>
                ) : (
                  <button
                    key={item}
                    type="button"
                    aria-current={item === meta.current_page ? 'page' : undefined}
                    onClick={() => setPage(item)}
                    className={[
                      'min-w-10 border px-3 py-2 text-sm font-medium transition-colors rounded-md',
                      item === meta.current_page
                        ? 'cursor-default border-primary bg-primary text-white'
                        : 'cursor-pointer border-line text-ink hover:bg-hover-tint',
                    ].join(' ')}
                  >
                    {item}
                  </button>
                ),
              )}
              <button
                type="button"
                disabled={meta.current_page >= meta.last_page}
                onClick={() => setPage((current) => Math.min(meta.last_page, current + 1))}
                className={paginationButtonClassName}
              >
                Next
              </button>
            </div>
          </div>
        </>
      )}
    </section>
  )
}
